// Regenerates src/schema-sql.ts from prisma/schema.prisma.
// Run after every schema change: node scripts/gen-schema.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const sql = execFileSync(
  'npx',
  ['prisma', 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/schema.prisma', '--script'],
  { encoding: 'utf8' },
);
const statements = sql
  .split(/;\s*\n/)
  .map((s) => s.replace(/^(\s*--.*\n)+/g, '').trim())
  .filter(Boolean)
  .map((s) =>
    s
      .replace(/^CREATE TABLE /, 'CREATE TABLE IF NOT EXISTS ')
      .replace(/^CREATE UNIQUE INDEX /, 'CREATE UNIQUE INDEX IF NOT EXISTS ')
      .replace(/^CREATE INDEX /, 'CREATE INDEX IF NOT EXISTS '),
  );
const body = `// GENERATED by scripts/gen-schema.mjs from prisma/schema.prisma. Do not edit.
// Idempotent DDL so the server can create its own schema on an empty database.
export const SCHEMA_STATEMENTS: string[] = ${JSON.stringify(statements, null, 2)};
`;
writeFileSync('src/schema-sql.ts', body);
console.log(`wrote ${statements.length} statements`);
